import fs from 'node:fs';
const html = fs.readFileSync(new URL('../ui/content-repurposer.html', import.meta.url), 'utf8');
const output = '// Generated by node scripts/build-content-repurposer-ui.mjs.\nexport const contentRepurposerHtml = ' + JSON.stringify(html) + ';\n';
const file = new URL('../src/content-repurposer-ui.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== output) throw new Error('Generated UI is stale');
  console.log('UI source and resource match');
} else fs.writeFileSync(file, output);
